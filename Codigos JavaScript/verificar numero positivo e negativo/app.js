let num = parseFloat(prompt("digite um número"));

if(num > 0){
    console.log(` O número digitado foi |${num}|, e ele é Positivo!!`);
}else if(num < 0){
    console.log(` O número digitado foi |${num}|, e ele é Negativo!!`);

}else{
    console.log(` O número digitado foi |${num}|, e ele é Zero (Null)!!`)
}

